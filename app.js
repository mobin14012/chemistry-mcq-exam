const BN_DIGITS = ["০","১","২","৩","৪","৫","৬","৭","৮","৯"];
function toBn(n){ return String(n).replace(/[0-9]/g, d=>BN_DIGITS[+d]); }
function toBnTime(sec){
  const m = Math.floor(sec/60), s = sec%60;
  return toBn(m)+":"+String(s).padStart(2,"0").replace(/[0-9]/g,d=>BN_DIGITS[+d]);
}
const DIFF_LABEL = {easy:"সহজ", tricky:"ট্রিকি", hard:"কঠিন"};

let currentSet = 1;
let answers = [];      // null | 0..3
let timerId = null;
let remaining = EXAM_MINUTES*60;
let startStamp = 0;
let submitted = false;
let lastResult = null;

const $ = id => document.getElementById(id);
const homeScreen=$("homeScreen"), examScreen=$("examScreen"), resultScreen=$("resultScreen");
const timerBox=$("timerBox"), timerText=$("timerText"), progressBar=$("progressBar"), progressFill=$("progressFill");

function show(screen){
  [homeScreen,examScreen,resultScreen].forEach(s=>s.classList.remove("active"));
  screen.classList.add("active");
  window.scrollTo({top:0, behavior:"smooth"});
}

document.querySelectorAll("[data-start]").forEach(btn=>{
  btn.addEventListener("click", ()=> startExam(parseInt(btn.dataset.start,10)));
});
$("backBtn").addEventListener("click", ()=>{ if(confirm("পরীক্ষা ছেড়ে হোমে যাবে? উত্তরগুলো মুছে যাবে।")) stopAndHome(); });
$("submitBtn").addEventListener("click", ()=>{ if(confirm("জমা দিতে চাও? এরপর উত্তর বদলানো যাবে না।")) finishExam(false); });
$("retryBtn").addEventListener("click", ()=> startExam(currentSet));
$("homeBtn").addEventListener("click", ()=> stopAndHome());

function stopAndHome(){
  clearInterval(timerId);
  timerBox.classList.add("hidden"); progressBar.classList.add("hidden");
  show(homeScreen);
}

function startExam(setNo){
  currentSet = setNo;
  answers = Array(TOTAL_Q).fill(null);
  submitted = false;
  remaining = EXAM_MINUTES*60;
  startStamp = Date.now();
  $("examTitle").textContent = "সেট–"+toBn(setNo)+" • ৩০টি প্রশ্ন • ৩৫ মিনিট";
  renderQuestions();
  show(examScreen);
  timerBox.classList.remove("hidden"); progressBar.classList.remove("hidden");
  updateTimerUI(); updateProgress();
  clearInterval(timerId);
  timerId = setInterval(()=>{
    remaining--;
    updateTimerUI();
    if(remaining<=0){ finishExam(true); }
  },1000);
}

function renderQuestions(){
  const list = $("questionList");
  list.innerHTML = "";
  SETS[currentSet].forEach((it, qi)=>{
    const card = document.createElement("div");
    card.className = "q-card unanswered";
    card.id = "qcard-"+qi;
    const opts = it.o.map((op, oi)=>{
      const bid = "q"+qi+"o"+oi;
      return `<label class="opt" id="${bid}-label">
        <input type="radio" name="q${qi}" value="${oi}">
        <span><b>(${["ক","খ","গ","ঘ"][oi]})</b> ${op}</span>
      </label>`;
    }).join("");
    card.innerHTML = `<div class="q-top"><span class="q-no">${toBn(qi+1)}</span>
      <span class="q-text">${it.q}</span>
      <span class="q-diff ${it.d}">${DIFF_LABEL[it.d]}</span></div>
      <div class="opts">${opts}</div>`;
    list.appendChild(card);
    card.querySelectorAll("input").forEach(inp=>{
      inp.addEventListener("change", ()=>{
        answers[qi] = parseInt(inp.value,10);
        card.classList.remove("unanswered");
        card.querySelectorAll(".opt").forEach(l=>l.classList.remove("selected"));
        $("q"+qi+"o"+answers[qi]+"-label").classList.add("selected");
        updateProgress();
      });
    });
  });
}

function updateTimerUI(){
  timerText.textContent = toBnTime(Math.max(0,remaining));
  timerBox.classList.toggle("danger", remaining<=60);
  timerBox.classList.toggle("warn", remaining>60 && remaining<=300);
}
function updateProgress(){
  const done = answers.filter(a=>a!==null).length;
  $("answeredCount").textContent = toBn(done)+" / "+toBn(TOTAL_Q)+" উত্তর";
  progressFill.style.width = (done/TOTAL_Q*100)+"%";
}

function grade(){
  let correct=0, wrong=0, skip=0;
  const rows = SETS[currentSet].map((it,qi)=>{
    const mine = answers[qi];
    let status = "skip";
    if(mine===null) skip++;
    else if(mine===it.a){ correct++; status="correct"; }
    else { wrong++; status="wrong"; }
    return {it, qi, mine, status};
  });
  return {correct, wrong, skip, rows};
}

function finishExam(auto){
  if(submitted) return;
  submitted = true;
  clearInterval(timerId);
  timerBox.classList.add("hidden"); progressBar.classList.add("hidden");
  const usedSec = Math.round((Date.now()-startStamp)/1000);
  const {correct, wrong, skip, rows} = grade();
  const pct = Math.round(correct/TOTAL_Q*100);
  lastResult = {correct, wrong, skip, rows, pct, usedSec, auto};
  renderResult(auto);
  show(resultScreen);
}

function gradeText(pct){
  if(pct>=90) return "🏆 অসাধারণ!";
  if(pct>=80) return "🌟 খুব ভালো!";
  if(pct>=70) return "👍 ভালো!";
  if(pct>=60) return "🙂 মোটামুটি ভালো";
  if(pct>=40) return "📖 আরও পড়তে হবে";
  return "💪 হাল ছেড়ো না, আবার চেষ্টা করো";
}

function renderResult(auto){
  const {correct, wrong, skip, pct, usedSec} = lastResult;
  const name = $("studentName").value.trim();
  $("resultTitle").textContent = "📊 সেট–"+toBn(currentSet)+" ফলাফল"+(auto?" (সময় শেষ — অটো জমা)":"");
  $("resultName").textContent = name ? name+"-এর পরীক্ষা • "+toBn(TOTAL_Q)+"টি প্রশ্ন • ৩৫ মিনিট" : toBn(TOTAL_Q)+"টি প্রশ্ন • ৩৫ মিনিটের পরীক্ষা";
  $("statCorrect").textContent = toBn(correct);
  $("statWrong").textContent = toBn(wrong);
  $("statSkip").textContent = toBn(skip);
  const mm = Math.floor(usedSec/60), ss = usedSec%60;
  $("statTime").textContent = toBn(mm)+":"+toBn(String(ss).padStart(2,"0"));
  $("scorePct").textContent = toBn(pct)+"%";
  $("scoreGrade").textContent = gradeText(pct)+" ("+toBn(correct)+"/"+toBn(TOTAL_Q)+")";
  const ring = document.querySelector(".score-ring");
  ring.style.background = `conic-gradient(${pct>=60?"#16a34a":pct>=40?"#d97706":"#dc2626"} ${pct}%, #e2e8f0 ${pct}%)`;
  renderReview("all");
  document.querySelectorAll("#filterRow .chip").forEach(c=>{
    c.classList.toggle("active", c.dataset.filter==="all");
    c.onclick = ()=>{
      document.querySelectorAll("#filterRow .chip").forEach(x=>x.classList.remove("active"));
      c.classList.add("active");
      renderReview(c.dataset.filter);
    };
  });
}

function renderReview(filter){
  const box = $("reviewList");
  box.innerHTML = "";
  const letters = ["ক","খ","গ","ঘ"];
  lastResult.rows
    .filter(r=> filter==="all" || r.status===filter)
    .forEach(({it, qi, mine, status})=>{
      const card = document.createElement("div");
      card.className = "q-card "+(status==="correct"?"correct":status==="wrong"?"wrong":"unanswered");
      const badge = status==="correct" ? `<span class="badge ok">✅ সঠিক</span>`
        : status==="wrong" ? `<span class="badge bad">❌ ভুল</span>`
        : `<span class="badge skip">⏭ বাদ পড়া</span>`;
      const opts = it.o.map((op, oi)=>{
        let cls = "opt";
        if(oi===it.a) cls += " right";
        if(mine===oi && oi!==it.a) cls += " wrong-pick";
        if(mine===oi && oi===it.a) cls += " selected";
        const mark = oi===it.a ? " ✅" : (mine===oi ? " ← তোমার উত্তর" : "");
        return `<div class="${cls}"><span><b>(${letters[oi]})</b> ${op}${mark}</span></div>`;
      }).join("");
      const yourLine = mine===null ? `<div class="your-ans muted">তোমার উত্তর: <b>দেওনি</b> • সঠিক: <b>(${letters[it.a]})</b></div>`
        : `<div class="your-ans">তোমার উত্তর: <b>(${letters[mine]})</b> • সঠিক: <b>(${letters[it.a]})</b></div>`;
      card.innerHTML = `<div class="q-top"><span class="q-no">${toBn(qi+1)}</span>
        <span class="q-text">${it.q}</span>
        <span class="q-diff ${it.d}">${DIFF_LABEL[it.d]}</span></div>
        ${badge}${yourLine}
        <div class="opts" style="margin-top:8px">${opts}</div>
        <div class="explain">💡 <b>ব্যাখ্যা:</b> ${it.e}</div>`;
      box.appendChild(card);
    });
  if(!box.children.length) box.innerHTML = `<p class="muted">এই ফিল্টারে কোনো প্রশ্ন নেই।</p>`;
}
